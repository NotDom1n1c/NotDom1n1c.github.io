  /* ---------- Umschaltlogik ---------- */

  var nodes = [].slice.call(document.querySelectorAll("[data-i18n]"));
  var buttons = [].slice.call(document.querySelectorAll(".lang__btn"));

  // Deutsch aus der Seite sichern, damit die Rueckkehr verlustfrei ist
  var de = {};
  nodes.forEach(function (n) {
    de[n.getAttribute("data-i18n")] = n.innerHTML;
  });

  function apply(lang) {
    if (lang !== "en" && lang !== "fr") lang = "de";
    var table = (lang === "de") ? de : DICT[lang];

    nodes.forEach(function (n) {
      var key = n.getAttribute("data-i18n");
      var val = table[key];
      if (val === undefined) val = de[key]; // Rueckfall auf Deutsch
      if (val !== undefined) n.innerHTML = val;
    });

    document.documentElement.setAttribute("lang", lang);

    buttons.forEach(function (b) {
      var on = b.getAttribute("data-lang") === lang;
      b.classList.toggle("is-active", on);
      b.setAttribute("aria-pressed", on ? "true" : "false");
    });

    try { localStorage.setItem(STORE, lang); } catch (e) { /* egal */ }
  }

  var start = "de";
  try {
    var saved = localStorage.getItem(STORE);
    if (saved) start = saved;
  } catch (e) { /* egal */ }

  apply(start);

  buttons.forEach(function (b) {
    b.addEventListener("click", function () {
      apply(b.getAttribute("data-lang"));
    });
  });
